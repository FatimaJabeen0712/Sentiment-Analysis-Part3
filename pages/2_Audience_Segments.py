# ------------------------------------------------------------------ Method
with tabs[5]:
    st.subheader("How it works")
    st.markdown("""
1. **Clean** comments with Part 1's cleaner (markup, empty, spam). Repeats are removed only when the same text appears on the *same post*, because "Price?" on different posts is a different shopper.
2. **Classify** each comment: language type (English / Roman Urdu / Urdu / Mixed), topic (price, discount, fabric, sizing, delivery, order status, availability, purchase interest, praise), purchase intent and sentiment. Topic rules are visible regular expressions; sentiment is Part 1's VADER plus Roman Urdu cues.
3. **Segment** comments with TF-IDF + SVD + k-means (k by silhouette), then name each cluster after the topic that dominates it.
4. **Compare content** with median engagement rate, bootstrap intervals and a Kruskal-Wallis test.
5. **Find unusual posts** against comparable posts with a robust z-score (median/MAD), a reach check, a complaint-share binomial test and an Isolation Forest as supporting evidence.
6. **Recommend** only when a rule has enough evidence, and say how confident it is and what could make it wrong.
""")
    st.subheader("Limits")
    st.markdown("""
- Instagram, TikTok and Facebook data cannot be collected automatically here (platform terms and access); use permitted exports and upload Tables A and B. The demo is simulated and labeled.
- Rules handle common English and Roman Urdu phrases; sarcasm, negation, typos and most Urdu script are only partly understood. No accuracy on real comments has been measured.
- Segments describe comments, not people. A comment asking for a discount is not a sale.
- Engagement rate is not sales. Posts without views are compared on raw interactions only.
""")
