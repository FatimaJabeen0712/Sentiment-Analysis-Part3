def read_csv(upload) -> pd.DataFrame:
    try:
        return pd.read_csv(upload, encoding="utf-8-sig")
    except Exception as exc:  # noqa: BLE001
        raise PipelineError(f"Could not read {getattr(upload, 'name', 'file')}: {exc}") from exc


def pct(x) -> str:
    return "n/a" if pd.isna(x) else f"{100 * x:.1f}%"


